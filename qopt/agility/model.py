"""
Coupled crypto-agility assignment model (Q-OPT v2 formulation).

Problem
-------
In every control epoch of length ``tau`` a key-management controller must
assign each service request r a *crypto option* o = (path, mode), with
mode in {QKD, PQC, HYB}. The decision variables are block-one-hot:

    y_{r,o} in {0,1},      sum_o y_{r,o} = 1     for every request r.

Why the v1 formulation was not enough
-------------------------------------
In Q-OPT v0.1 every cost term was a property of a single option, so the
QUBO was block-separable: the global optimum is obtained by picking the
cheapest option of each request independently (greedy == exact, which is
precisely what tables/solver_comparison_summary.csv showed). Such a
problem has no combinatorial content and cannot motivate any optimizer,
quantum or classical.

The physical resources that make crypto-agility hard are *shared*:

  * QKD key material on a link is a finite budget B_e (bits) per epoch
    (pool level + secret-key generation over the epoch). Trusted-node
    relaying consumes key on every hop, so every QKD/HYB request routed
    over link e draws from the same budget.
  * PQC handshakes consume CPU on the end nodes.
  * Every PQC/HYB handshake consumes fresh entropy from the node QRNG.

We model each shared resource with a convex quadratic congestion
surrogate on its utilisation u = load / budget,

    J_link = w_K * sum_e (L_e(y) / B_e)^2,
    J_cpu  = w_C * sum_n (C_n(y) / Cap_n)^2,
    J_rng  = w_Q * sum_n (H_n(y) / Ent_n)^2,

which couples every pair of requests that compete for the same resource.
The total cost is

    E(y) = sum_i c_i y_i + y^T W y ,

with c the option-local cost (risk, latency/SLA, security-floor penalty)
and W the coupling matrix generated by the three congestion terms. The
evaluation simulator (qopt.agility.twin) enforces *hard* budgets, so the
quadratic surrogate is never confused with the metric it is meant to
improve.

Risk model
----------
  * QKD over path P with trusted relays: the key is exposed on every link
    and at every intermediate trusted node,
        rho_Q(P) = 1 - prod_e (1 - rho_e) * prod_{n in int(P)} (1 - rho_n).
  * PQC: rho_P, the probability that the KEM is broken (cryptanalysis,
    implementation/side-channel failure) within the confidentiality
    lifetime of the traffic. A scenario parameter.
  * HYB: a dual-PRF / concatenation KDF combiner (NIST SP 800-56C r2,
    ETSI TS 103 744) is secure if either input is secret. Under the
    independence assumption, rho_H = rho_Q * rho_P.

Every option is also charged an SLA term and a soft security-floor
penalty that activates when its risk exceeds the class tolerance.
"""
from __future__ import annotations

from dataclasses import dataclass, field
from itertools import islice

import networkx as nx
import numpy as np

from qopt.qkd.channel import ChannelParams, key_generation_rate_bps

MODES = ("QKD", "PQC", "HYB")

# Maximum tolerable per-epoch compromise probability by service class.
CLASS_TOLERANCE = {"critical": 0.004, "high": 0.015, "normal": 0.05, "best_effort": 0.25}
CLASS_PROBS = {"critical": 0.2, "high": 0.3, "normal": 0.35, "best_effort": 0.15}


# --------------------------------------------------------------------------- #
# Scenario description
# --------------------------------------------------------------------------- #
@dataclass
class ScenarioParams:
    """All physical / operational constants of one scenario (documented units)."""
    epoch_s: float = 1.0                 # control epoch tau [s]
    key_rate_scale: float = 2e-3         # system efficiency x duty cycle x finite-size factor
    pool_capacity_s: float = 3.0         # pool capacity, in epochs of nominal generation
    rho_pqc: float = 0.02                # P(PQC broken within data lifetime)
    rho_trusted_node: float = 0.002      # per-epoch trusted-relay compromise probability
    prop_ms_per_km: float = 0.005        # fibre propagation
    kms_relay_ms: float = 1.5            # per-hop KMS key relay latency (QKD / HYB)
    pqc_handshake_ms: float = 2.0        # ML-KEM-768 handshake incl. one RTT, end-to-end
    hyb_combine_ms: float = 0.2          # KDF combiner
    cpu_per_handshake: float = 1.0       # CPU units per PQC handshake (one end)
    rng_bits_pqc: float = 512.0          # entropy per ML-KEM handshake [bits]
    rng_bits_qkd_relay: float = 0.0      # QKD relays need no handshake entropy
    node_cpu_capacity: float = 4.0       # CPU units per node per epoch
    node_rng_capacity: float = 2048.0    # QRNG output per node per epoch [bits]
    min_budget_bits: float = 1.0         # floor used when a link is aborted
    channel: ChannelParams = field(default_factory=ChannelParams)


DEFAULT_WEIGHTS = dict(w_R=1.0, w_L=0.25, w_S=4.0, w_K=1.5, w_C=0.5, w_Q=0.5)


@dataclass
class Request:
    req_id: int
    source: int
    dest: int
    demand_bits: float        # key material needed this epoch (per hop, OTP relay)
    handshakes: float         # PQC handshakes needed this epoch
    service_class: str
    latency_sla_ms: float

    @property
    def tolerance(self) -> float:
        return CLASS_TOLERANCE[self.service_class]


@dataclass
class LinkState:
    length_km: float
    qber_shift: float = 0.0
    attack_prob: float = 0.0
    trust: float = 1.0
    pool_bits: float = 0.0
    # derived
    rate_bps: float = 0.0
    qber: float = 0.0
    rho: float = 0.0
    budget_bits: float = 0.0


@dataclass
class Option:
    block: int
    path: tuple
    mode: str
    edges: tuple
    risk: float
    latency_ms: float
    key_bits_per_edge: float
    cpu_nodes: dict
    rng_nodes: dict
    local_cost: float = 0.0


@dataclass
class AgilityProblem:
    """A block-one-hot quadratic program  min_y c.y + y^T W y,  one-hot per block."""
    requests: list
    options: list                 # flattened, block-major
    blocks: list                  # blocks[r] = list of global option indices
    c: np.ndarray                 # (n,) option-local cost
    W: np.ndarray                 # (n, n) symmetric coupling (diag = self-congestion)
    links: dict
    params: ScenarioParams
    weights: dict

    @property
    def n(self) -> int:
        return len(self.options)

    @property
    def block_sizes(self) -> list:
        return [len(b) for b in self.blocks]

    @property
    def n_feasible(self) -> int:
        return int(np.prod(self.block_sizes, dtype=np.int64))

    # ---- energies ---------------------------------------------------------
    def energy_y(self, y: np.ndarray) -> float:
        y = np.asarray(y, dtype=float)
        return float(self.c @ y + y @ self.W @ y)

    def energy_choice(self, choice) -> float:
        """choice[r] = local index of the option picked in block r."""
        idx = np.array([self.blocks[r][k] for r, k in enumerate(choice)])
        return float(self.c[idx].sum() + self.W[np.ix_(idx, idx)].sum())

    def energies_batch(self, choices: np.ndarray) -> np.ndarray:
        """Vectorised energies for an (M, R) array of local choices."""
        choices = np.asarray(choices)
        offs = np.array([b[0] for b in self.blocks])
        g = choices + offs[None, :]                 # global indices (blocks are contiguous)
        e = self.c[g].sum(axis=1)
        R = g.shape[1]
        for a in range(R):
            e += self.W[g[:, a][:, None], g].sum(axis=1)
        return e

    def choice_to_y(self, choice) -> np.ndarray:
        y = np.zeros(self.n)
        for r, k in enumerate(choice):
            y[self.blocks[r][k]] = 1.0
        return y

    def y_to_choice(self, y) -> list | None:
        out = []
        for b in self.blocks:
            on = [k for k, i in enumerate(b) if y[i] > 0.5]
            if len(on) != 1:
                return None
            out.append(on[0])
        return out

    # ---- QUBO / Ising views ----------------------------------------------
    def qubo_penalized(self, penalty: float) -> tuple[np.ndarray, float]:
        """Full-space QUBO with one-hot penalty: returns (Q upper-triangular, offset)."""
        Q = np.zeros((self.n, self.n))
        Q[np.diag_indices(self.n)] += self.c + np.diag(self.W)
        iu = np.triu_indices(self.n, 1)
        Q[iu] += 2.0 * self.W[iu]
        offset = 0.0
        for b in self.blocks:
            for i in b:
                Q[i, i] -= penalty
            for a in range(len(b)):
                for bb in range(a + 1, len(b)):
                    Q[b[a], b[bb]] += 2.0 * penalty
            offset += penalty
        return Q, offset

    def qubo_feasible_compressed(self) -> tuple[np.ndarray, float]:
        """
        QUBO that reproduces E(y) exactly on the one-hot subspace with all
        intra-block couplings removed (y_i y_j = 0 there). Used by the
        constraint-preserving ansatz: fewer two-qubit cost terms.
        """
        Q = np.zeros((self.n, self.n))
        Q[np.diag_indices(self.n)] += self.c + np.diag(self.W)
        blk = np.empty(self.n, dtype=int)
        for r, b in enumerate(self.blocks):
            blk[b] = r
        for i in range(self.n):
            for j in range(i + 1, self.n):
                if blk[i] != blk[j] and self.W[i, j] != 0.0:
                    Q[i, j] += 2.0 * self.W[i, j]
        return Q, 0.0


# --------------------------------------------------------------------------- #
# Builders
# --------------------------------------------------------------------------- #
def k_shortest_paths(G: nx.Graph, s: int, d: int, k: int) -> list[tuple]:
    try:
        return [tuple(p) for p in islice(nx.shortest_simple_paths(G, s, d, weight="length_km"), k)]
    except nx.NetworkXNoPath:
        return []


def _edges(path):
    return tuple(frozenset((path[i], path[i + 1])) for i in range(len(path) - 1))


def link_compromise_prob(ls: LinkState, qber_abort: float) -> float:
    """
    Per-epoch probability that key material relayed over the link is
    exposed. An active adversary is detected with a probability that grows
    with the QBER she induces; residual exposure is attack_prob times the
    undetected fraction, plus a trust term for the link's control plane.
    """
    detect = np.clip(ls.qber / qber_abort, 0.0, 1.0)
    exposure = ls.attack_prob * (1.0 - 0.8 * detect)
    control = 0.02 * (1.0 - ls.trust)
    return float(np.clip(1.0 - (1.0 - exposure) * (1.0 - control), 0.0, 1.0))


def refresh_links(G: nx.Graph, links: dict, params: ScenarioParams) -> dict:
    """Recompute derived link quantities (rate, QBER, risk, budget) in place."""
    cap_cache = {}
    for e, ls in links.items():
        rate, _, qber = key_generation_rate_bps(ls.length_km, params.channel, qber_shift=ls.qber_shift)
        ls.rate_bps = rate * params.key_rate_scale
        ls.qber = qber
        ls.rho = link_compromise_prob(ls, qber_abort=0.11)
        ls.budget_bits = max(ls.pool_bits + ls.rate_bps * params.epoch_s, params.min_budget_bits)
        cap_cache[e] = ls
    return links


def nominal_pool_capacity(ls: LinkState, params: ScenarioParams) -> float:
    rate, _, _ = key_generation_rate_bps(ls.length_km, params.channel)
    return rate * params.key_rate_scale * params.epoch_s * params.pool_capacity_s


def build_problem(G: nx.Graph, requests: list, links: dict,
                  params: ScenarioParams | None = None, weights: dict | None = None,
                  k_paths: int = 1, modes=MODES) -> AgilityProblem:
    params = params or ScenarioParams()
    weights = {**DEFAULT_WEIGHTS, **(weights or {})}
    options, blocks = [], []
    for r, req in enumerate(requests):
        paths = k_shortest_paths(G, req.source, req.dest, k_paths)
        blk = []
        for path in paths:
            edges = _edges(path)
            prop = sum(G[path[i]][path[i + 1]]["length_km"] for i in range(len(path) - 1)) * params.prop_ms_per_km
            surv = np.prod([1.0 - links[e].rho for e in edges])
            surv *= (1.0 - params.rho_trusted_node) ** max(len(path) - 2, 0)
            rho_q = 1.0 - surv
            for mode in modes:
                if mode == "QKD":
                    risk, kb = rho_q, req.demand_bits
                    lat = prop + params.kms_relay_ms * len(edges)
                    cpu, rng = {}, {}
                elif mode == "PQC":
                    risk, kb = params.rho_pqc, 0.0
                    lat = prop + params.pqc_handshake_ms
                    load = req.handshakes * params.cpu_per_handshake
                    cpu = {req.source: load, req.dest: load}
                    rng = {req.source: req.handshakes * params.rng_bits_pqc,
                           req.dest: req.handshakes * params.rng_bits_pqc}
                else:  # HYB
                    risk, kb = rho_q * params.rho_pqc, req.demand_bits
                    lat = prop + max(params.kms_relay_ms * len(edges), params.pqc_handshake_ms) + params.hyb_combine_ms
                    load = req.handshakes * params.cpu_per_handshake
                    cpu = {req.source: load, req.dest: load}
                    rng = {req.source: req.handshakes * params.rng_bits_pqc,
                           req.dest: req.handshakes * params.rng_bits_pqc}
                opt = Option(block=r, path=path, mode=mode, edges=edges, risk=float(risk),
                             latency_ms=float(lat), key_bits_per_edge=float(kb), cpu_nodes=cpu, rng_nodes=rng)
                tol = req.tolerance
                sla = lat / req.latency_sla_ms
                opt.local_cost = (weights["w_R"] * risk / tol            # risk in units of the class tolerance
                                  + weights["w_L"] * (sla + 4.0 * max(sla - 1.0, 0.0))
                                  + weights["w_S"] * max(risk / tol - 1.0, 0.0))
                blk.append(len(options))
                options.append(opt)
        if not blk:
            raise ValueError(f"request {r}: no path between {req.source} and {req.dest}")
        blocks.append(blk)

    n = len(options)
    c = np.array([o.local_cost for o in options])
    W = np.zeros((n, n))
    # Shared QKD key budget per link
    for e, ls in links.items():
        a = np.array([o.key_bits_per_edge if e in o.edges else 0.0 for o in options]) / ls.budget_bits
        if a.any():
            W += weights["w_K"] * np.outer(a, a)
    # Node CPU and QRNG entropy
    for node in G.nodes():
        a = np.array([o.cpu_nodes.get(node, 0.0) for o in options]) / params.node_cpu_capacity
        if a.any():
            W += weights["w_C"] * np.outer(a, a)
        h = np.array([o.rng_nodes.get(node, 0.0) for o in options]) / params.node_rng_capacity
        if h.any():
            W += weights["w_Q"] * np.outer(h, h)
    return AgilityProblem(requests=list(requests), options=options, blocks=blocks, c=c, W=W,
                          links=links, params=params, weights=weights)


# --------------------------------------------------------------------------- #
# Random scenario generator (used by experiments and tests)
# --------------------------------------------------------------------------- #
def sample_requests(G: nx.Graph, n_requests: int, rng: np.random.Generator,
                    links: dict, params: ScenarioParams, load: float = 1.0,
                    hotspot: tuple | None = None) -> list[Request]:
    """
    Requests are scaled to the *network's* key supply so that 'load' has a
    physical meaning: load=1 means the mean per-request demand equals the
    mean link budget divided by the number of requests.
    """
    nodes = list(G.nodes())
    mean_budget = np.mean([ls.budget_bits for ls in links.values()])
    classes = list(CLASS_PROBS)
    probs = np.array([CLASS_PROBS[c] for c in classes])
    reqs = []
    for i in range(n_requests):
        if hotspot is not None and rng.random() < 0.5:
            s, d = hotspot
        else:
            s, d = rng.choice(nodes, size=2, replace=False)
        cls = str(rng.choice(classes, p=probs))
        demand = float(load * mean_budget / max(n_requests, 1) * rng.uniform(0.5, 1.5) * 2.0)
        reqs.append(Request(i, int(s), int(d), demand, float(rng.integers(1, 3)), cls,
                            float(rng.uniform(4.0, 25.0))))
    return reqs


def make_links(G: nx.Graph, params: ScenarioParams, rng: np.random.Generator,
               attacked_frac: float = 0.0, attack_intensity: float = 0.0,
               pool_frac: tuple = (0.2, 0.8)) -> dict:
    links = {}
    edges = list(G.edges())
    n_att = int(round(attacked_frac * len(edges)))
    attacked = set(map(int, rng.choice(len(edges), size=n_att, replace=False))) if n_att else set()
    for k, (u, v) in enumerate(edges):
        ls = LinkState(length_km=float(G[u][v]["length_km"]))
        if k in attacked:
            ls.qber_shift = 0.05 * attack_intensity * rng.uniform(0.5, 1.0)
            ls.attack_prob = attack_intensity * rng.uniform(0.4, 1.0)
            ls.trust = 1.0 - 0.5 * attack_intensity
        ls.pool_bits = nominal_pool_capacity(ls, params) * rng.uniform(*pool_frac)
        links[frozenset((u, v))] = ls
    return refresh_links(G, links, params)


def random_instance(topology: str = "C", n_requests: int = 4, k_paths: int = 1, seed: int = 0,
                    load: float = 1.0, attacked_frac: float = 0.3, attack_intensity: float = 0.6,
                    params: ScenarioParams | None = None, weights: dict | None = None,
                    hotspot: bool = True) -> AgilityProblem:
    from qopt.network.topology import get_topology
    params = params or ScenarioParams()
    rng = np.random.default_rng(seed)
    G = get_topology(topology, seed=seed)
    links = make_links(G, params, rng, attacked_frac, attack_intensity)
    hs = None
    if hotspot:
        u, v = list(G.edges())[int(rng.integers(G.number_of_edges()))]
        hs = (int(u), int(v))
    reqs = sample_requests(G, n_requests, rng, links, params, load=load, hotspot=hs)
    prob = build_problem(G, reqs, links, params, weights, k_paths=k_paths)
    prob.graph = G
    return prob
